DEFAULT_PERSONAS: list[str] = [
    "diligent_strong",
    "minimalist_weak",
    "rule_lawyer",
    "ambiguity_prober",
]


def resolve_personas(keys: list[str] | None) -> list[Persona]:
    if not keys:
        keys = DEFAULT_PERSONAS
    unknown = [k for k in keys if k not in PERSONAS]
    if unknown:
        raise ValueError(f"неизвестные профили решателей: {unknown}. Доступны: {list(PERSONAS)}")
    return [PERSONAS[k] for k in keys]
