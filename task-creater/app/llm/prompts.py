def critic_user(
    data: TaskDraftData,
    criteria: list[Criterion],
    gradings: list[GraderOutput],
    solvers: list[SolverOutput],
    focus: str = "",
) -> str:
    grading_dump = json.dumps([g.model_dump() for g in gradings], ensure_ascii=False, indent=1)
    guesses = [
        {"persona": s.persona, "where_brief_fell_short": s.exploited_ambiguities}
        for s in solvers
        if s.exploited_ambiguities
    ]
    return f"""\
{focus}

Студенческий бриф:
{student_brief_md(data, criteria)}

ПОЛНАЯ рубрика (скрыта от студента):
<CRITERIA_JSON>{hidden_rubric_json(criteria)}</CRITERIA_JSON>

Предварительное ревью разных решений по этой рубрике:
{grading_dump}

Где решатели сами отметили, что брифа не хватило:
{json.dumps(guesses, ensure_ascii=False, indent=1)}
"""


