"""Сколько экономит автоматизация — в часах и в деньгах.

Числа «до» здесь не выдуманы и не взяты из головы: это то, что кейсодатель и
ревьюер сказали на интервью. Каждый ориентир подписан источником, потому что
именно на них считается экономический эффект, а цифра без источника в такой
таблице — самая дорогая ошибка из возможных.

Числа «после» сюда не попадают вовсе: их измеряет `scripts/measure_pipeline.py`
на живом сервисе и приносит в готовом виде. Смешивать замер с ориентиром в
одном файле нельзя — их разное происхождение и есть главное, что нужно видеть.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Baseline:
    """Ручной ориентир: сколько это занимает у человека и откуда мы это знаем."""

    operation: str
    minutes: float
    source: str
    note: str = ""


# --------------------------------------------------------------------------- #
#  Ориентиры «как было»
# --------------------------------------------------------------------------- #

BASELINES = (
    Baseline(
        operation="review",
        minutes=60.0,
        source="Интервью с ревьюером, 2026-09-03",
        note="«До автоматизации одна работа могла занимать около 1 часа»; "
        "больше всего времени уходило на формирование обратной связи",
    ),
    Baseline(
        operation="review_with_ai",
        minutes=12.5,
        source="Интервью с ревьюером, 2026-09-03",
        note="10–15 минут на работу на курсе, где AI-проверку уже внедрили "
        "своими силами; взята середина диапазона",
    ),
)

BASELINE_BY_OPERATION = {item.operation: item for item in BASELINES}

# Недельная нагрузка из описания кейса — по ней считается охват, а не разовая
# экономия: «5–10 часов в неделю» у эксперта и «до 10 часов» у методиста.
WEEKLY_HOURS = {"reviewer": (5.0, 10.0), "methodist": (0.0, 10.0)}


# --------------------------------------------------------------------------- #
#  Счёт
# --------------------------------------------------------------------------- #


def saved_minutes(manual_minutes: float, machine_seconds: float, human_minutes: float) -> float:
    """Сколько минут экономит одна операция.

    `human_minutes` — то, что человек всё равно тратит после машины: проверить
    и принять решение. Вычитать его обязательно. Разница между «машина считает
    40 секунд» и «работа проверена за 40 секунд» — это ровно то место, где
    экономический расчёт превращается в рекламу.
    """

    after = machine_seconds / 60 + human_minutes
    return round(manual_minutes - after, 2)


def cost_usd(tokens_in: int, tokens_out: int, *, price_in: float, price_out: float) -> float:
    """Стоимость вызова по тарифу за миллион токенов."""

    return round((tokens_in * price_in + tokens_out * price_out) / 1_000_000, 6)


def payback_ratio(saved_minutes_value: float, cost: float, hourly_rate: float) -> float | None:
    """Во сколько раз сэкономленное время дороже потраченных денег.

    Ставка задаётся снаружи и не хранится в коде: своих ставок Авито не
    раскрывал, а подставить «примерно рыночную» и выдать результат за расчёт —
    значит соврать в самой важной строке таблицы.
    """

    if cost <= 0 or hourly_rate <= 0:
        return None
    return round((saved_minutes_value / 60 * hourly_rate) / cost, 1)
