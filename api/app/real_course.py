"""Каталог реального курса: задания, критерии и решения студентов.

Источник — `Product-part/01_Входящие/homework_examples`: материалы, которые
кейсодатель передал вместе с постановкой задачи. Здесь ничего не придумано:
формулировки заданий и решения берутся из файлов как есть, а критерии
переписаны из раздела «Критерии оценивания» соответствующего условия — вручную,
с сохранением названий и весов.

Почему критерии не разбираются из документа программой. Условия приходят в
пяти форматах, и в каждом критерии оформлены по-своему: где-то таблица
markdown, где-то таблица Word, где-то абзацы «— 2 балла» в конце текста.
Регулярное выражение по такому набору ошибётся молча, а ошибка здесь — это не
кривая строка на экране, а неверная шкала, по которой поставят оценку живому
человеку. Поэтому шкала переносится глазами и лежит в коде, где её видно на
ревью, а не собирается на лету.

Единственная правка против источника отмечена комментарием в самом критерии.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Solution:
    """Решение студента. `level` — оценка качества, данная самим кейсодателем."""

    level: str          # weak | medium | strong
    path: str           # относительно каталога homework_examples
    label: str          # как решение названо в источнике


@dataclass(frozen=True)
class Task:
    slug: str
    title: str
    track: str
    topic: str
    statement_path: str
    criteria: list[dict]
    solutions: list[Solution]
    pass_score: float | None = None   # None — взять 60% от максимума
    effort_weight: float = 1.0
    note: str = ""
    statement_from: str = ""          # с какого заголовка начинать текст условия
    extras: dict = field(default_factory=dict)

    @property
    def max_score(self) -> float:
        return round(sum(item["max_score"] for item in self.criteria), 2)


def criterion(key: str, title: str, max_score: float, levels: list[dict] | None = None) -> dict:
    item = {"key": key, "title": title, "max_score": max_score}
    if levels:
        item["levels"] = levels
    return item


