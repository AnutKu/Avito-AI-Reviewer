const KEY = 'avito-onboarding-seen'

export const stepsFor = (role) => ONBOARDING[role]?.steps || []
export const titleFor = (role) => ONBOARDING[role]?.title || 'Как устроен кабинет'

// Хранилище может быть недоступно (приватное окно, запрет на данные сайта).
// Тогда онбординг покажется ещё раз — это неприятно, но безопасно; падать
// из-за него нельзя.
export function wasSeen(role) {
  try {
    return (localStorage.getItem(KEY) || '').split(',').includes(role)
  } catch { return false }
}

export function markSeen(role) {
  try {
    const seen = new Set((localStorage.getItem(KEY) || '').split(',').filter(Boolean))
    seen.add(role)
    localStorage.setItem(KEY, [...seen].join(','))
  } catch { /* не показать второй раз — меньшее зло, чем упасть */ }
}

// Показывать ли при входе: только знакомым ролям и только в первый раз.
export const shouldShow = (role) => !!ONBOARDING[role] && !wasSeen(role)
