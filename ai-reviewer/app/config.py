from typing import Literal

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    zai_api_key: str | None = None
    zai_model: str = "glm-5.3-flash"
    zai_reasoning_effort: Literal["low", "medium", "high", "max"] = "low"
    zai_timeout_seconds: float = 120.0
    # Один и тот же MAX_SNAPSHOT_CHARS читают core api (режет при сборке снапшота)
    # и этот сервис (страховка перед отправкой в модель). Значения обязаны совпадать,
    # иначе часть снапшота молча не доедет до модели.
    max_snapshot_chars: int = 120_000

    # Сколько прогонов детектора голосует за вердикт. Три — минимум, на котором
    # большинство вообще возможно: на двух любое расхождение даёт ничью.
    # Прогоны идут параллельно, поэтому цена нечётного числа — токены, а не
    # ожидание; чётные значения допустимы, но большинство на них хуже.
    detection_votes: int = Field(default=3, ge=1, le=5)

    # Маскирование перед отправкой в Z.AI. Выключено по умолчанию намеренно:
    # бандл модели весит 700 МБ, в образ не входит и монтируется снаружи, а
    # сервис обязан подниматься и без него. Включается явно — в compose.
    # Включённое и неработающее маскирование НЕ пропускает запрос к провайдеру:
    # см. masking.MaskingUnavailable.
    masking_enabled: bool = False
    masking_model_path: str = "/srv/anonimaze_model"
    masking_device: str = "cpu"
    # Что заменяем плейсхолдерами: восемь меток обученной модели.
    #
    # Метки SECRET здесь НЕТ, и это измеренное решение, а не забывчивость.
    # SECRET приходит только от детерминированного слоя и означает «непрозрачное
    # значение, тип установить не удалось». На домашней работе по ML это метка
    # почти всего подряд: прогон по двум настоящим ноутбукам курса (17.8 тыс.
    # символов) дал 33 спана, из них 29 — SECRET, и среди них ни одного
    # настоящего секрета: имена моделей (Qwen3ForCausalLM,
    # ai-forever/rugpt3small_based_on_gpt2), пути к чекпоинтам и ГОЛЫЕ ЧИСЛА
    # (10, 42, 100, 150). Замаскировать гиперпараметры значит отдать модели
    # текст, по которому разбор невозможен, — ради нуля найденных секретов.
    #
    # Типизированные метки того же слоя (PASSWORD, SECRET_KEY по kv и cli)
    # остаются: на настоящем `password = "..."` они и срабатывают, а их редкий
    # промах вроде tokenizer.pad_token_id стоит одного токена в файле.
    masking_labels: list[str] = [
        "PERSON",
        "LOCATION",
        "ORGANIZATION",
        "CONTRACT_NUMBER",
        "LOGIN",
        "PASSWORD",
        "AUTH_TOKEN",
        "SECRET_KEY",
    ]
    # Пороги отсева — ТОЛЬКО для спанов, найденных одной NER-половиной. То, что
    # подтвердил детерминированный слой (source regex/both), проходит всегда:
    # у правила нет вероятности, и порогом его резать нечем.
    #
    # На коде NER заражается контекстом: после настоящей строки
    # `password = "..."` она продолжает метить PASSWORD и на следующих строках.
    # Замерено на тексте «секрет + гиперпараметры»: мусор идёт с уверенностью
    # 0.52 ('seed = 42') и 0.62 ('s' внутри 'epochs'), настоящие ПДн и
    # секреты — с 0.67 и выше (имя 0.67, логин 0.71, договор 0.74, дальше 0.9+).
    #
    # Порог низкий намеренно. Ошибки здесь несимметричны: лишний спан стоит
    # качества разбора, пропущенный — утечки. Поэтому режем только явный шум.
    masking_min_score: float = 0.6
    # Однобуквенный «пароль» — не секрет, а обрезок соседнего слова: NER рвёт
    # границы спанов, и такой огрызок портит слово, ничего не защищая.
    masking_min_length: int = 3


settings = Settings()
